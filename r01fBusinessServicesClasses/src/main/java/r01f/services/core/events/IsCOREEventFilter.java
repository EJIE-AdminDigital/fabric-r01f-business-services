package r01f.services.core.events;

import r01f.eventbus.Event;

public interface IsCOREEventFilter<E extends Event> {
/////////////////////////////////////////////////////////////////////////////////////////
//	
/////////////////////////////////////////////////////////////////////////////////////////
	public boolean hasTobeHandled(E opEvent);
	
	public default IsCOREEventFilter<E> joinedWith(final IsCOREEventFilter<E> other) {
		return event -> this.hasTobeHandled(event)
					 && other.hasTobeHandled(event);
	}
/////////////////////////////////////////////////////////////////////////////////////////
//	
/////////////////////////////////////////////////////////////////////////////////////////	
	public static <E extends Event> IsCOREEventFilter<E> handleAll() {
		return event -> true;
	}
}
